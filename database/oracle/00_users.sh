#!/usr/bin/env bash
set -euo pipefail
[[ "$DEMO_READER_PASSWORD" =~ ^Aa1[0-9a-f]{24}$ ]] || exit 2
sqlplus -s '/ as sysdba' <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER = XEPDB1;
CREATE USER ACADEMIC_OWNER NO AUTHENTICATION DEFAULT TABLESPACE USERS QUOTA 10M ON USERS;
CREATE USER ACADEMIC_READER IDENTIFIED BY "$DEMO_READER_PASSWORD";
GRANT CREATE SESSION TO ACADEMIC_READER;
EXIT
SQL
